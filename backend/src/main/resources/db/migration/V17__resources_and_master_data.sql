CREATE SEQUENCE clinic_resource_id_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE clinic_resources (
 id BIGINT DEFAULT nextval('clinic_resource_id_seq') PRIMARY KEY,
 branch_id BIGINT NOT NULL REFERENCES branches(id), code VARCHAR(40) NOT NULL UNIQUE,
 name VARCHAR(120) NOT NULL, type VARCHAR(30) NOT NULL, status VARCHAR(30) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_clinic_resources_branch ON clinic_resources(branch_id);

CREATE SEQUENCE master_data_id_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE master_data (
 id BIGINT DEFAULT nextval('master_data_id_seq') PRIMARY KEY,
 category VARCHAR(60) NOT NULL, code VARCHAR(60) NOT NULL, name VARCHAR(160) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_master_data_category_code UNIQUE(category, code)
);
