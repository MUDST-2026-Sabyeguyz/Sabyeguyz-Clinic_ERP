CREATE SEQUENCE app_user_id_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE app_users (
 id BIGINT DEFAULT nextval('app_user_id_seq') PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(30) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE staff (
 id BIGINT PRIMARY KEY REFERENCES app_users(id),
 employee_code VARCHAR(40) NOT NULL UNIQUE,
 full_name VARCHAR(160) NOT NULL,
 phone VARCHAR(40),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE SEQUENCE treatment_id_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE treatments (
 id BIGINT DEFAULT nextval('treatment_id_seq') PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patients(id),
 appointment_id BIGINT REFERENCES appointments(id),
 staff_id BIGINT REFERENCES staff(id),
 service VARCHAR(120) NOT NULL,
 note TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
