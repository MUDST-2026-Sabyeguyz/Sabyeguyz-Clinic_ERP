  docker(['config', '--quiet'])
  console.log('Building/starting disposable Compose project: ' + project)
  docker(['up', '--build', '-d', '--wait', '--wait-timeout', '300'], true)
  const frontend = 'http://' + docker(['port', 'frontend', '80'])
  const backend = 'http://' + docker(['port', 'backend', '8080'])
