import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const project = 'clinic-phase1-compose-' + randomBytes(6).toString('hex')
const directory = path.join(root, 'artifacts', 'compose', project)
fs.mkdirSync(directory, { recursive: true })
const env = { ...process.env, POSTGRES_DB: 'clinic_erp_v2', POSTGRES_USER: 'clinic', POSTGRES_PASSWORD: randomBytes(32).toString('hex'), JWT_SECRET: randomBytes(32).toString('hex'), POSTGRES_PORT: '127.0.0.1:0', BACKEND_PORT: '127.0.0.1:0', FRONTEND_PORT: '127.0.0.1:0' }
const args = ['compose', '-p', project, '-f', 'compose.yaml', '-f', 'compose.phase1-demo.yaml']
const result = { project, sourceSha: spawnSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).stdout?.trim(), startedUtc: new Date().toISOString(), checks: {}, syntheticOnly: true }
result.gitStatus = spawnSync('git', ['status', '--porcelain'], { cwd: root, encoding: 'utf8' }).stdout?.trim()
result.codeFingerprints = Object.fromEntries(['backend', 'frontend'].map(directory => {
  const hash = createHash('sha256')
  const files = spawnSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z', '--', directory], { cwd: root, encoding: 'utf8' }).stdout.split('\0').filter(Boolean).sort()
  for (const file of files) { hash.update(file + '\0'); hash.update(fs.readFileSync(path.join(root, file))) }
  return [directory, hash.digest('hex')]
}))
function docker(command, logged = false) {
  const fd = logged ? fs.openSync(path.join(directory, command[0] + '.log'), 'w') : null
  const r = spawnSync('docker', [...args, ...command], { cwd: root, env, encoding: 'utf8', windowsHide: true, ...(logged ? { stdio: ['ignore', fd, fd] } : {}) })
  if (fd != null) fs.closeSync(fd)
  if (r.status !== 0) throw Error('Compose ' + command[0] + ' failed; inspect its stage log')
  return r.stdout?.trim()
}
